impl Provider {
    /// Parse a provider from its name and parameters.
    pub fn parse(name: &str, params: &Params) -> Result<Provider> {
        let lower = name.trim().to_ascii_lowercase();
        let p = match canonical(&lower) {
            "first_name" => Provider::FirstName,
            "last_name" => Provider::LastName,
            "name" => Provider::Name,
            "username" => Provider::Username,
            "email" => Provider::Email,
            "phone_number" => Provider::PhoneNumber,
            "ipv4" => Provider::Ipv4,
            "ipv6" => Provider::Ipv6,
            "mac_address" => Provider::MacAddress,
            "domain_name" => Provider::DomainName,
            "url" => Provider::Url,
            "user_agent" => Provider::UserAgent,
            "uuid4" => Provider::Uuid4,
            "uuid7" => Provider::Uuid7,
            "street_address" => Provider::StreetAddress,
            "city" => Provider::City,
            "state" => Provider::State,
            "state_abbr" => Provider::StateAbbr,
            "postcode" => Provider::Postcode,
            "country" => Provider::Country,
            "country_code" => Provider::CountryCode,
            "address" => Provider::Address,
            "company" => Provider::Company,
            "job_title" => Provider::JobTitle,
            "latitude" => Provider::Latitude,
            "longitude" => Provider::Longitude,
            "credit_card_number" => Provider::CreditCardNumber,
            "currency_code" => Provider::CurrencyCode,
            "price" => {
                let min = p_f64(params, "min", 1.0)?;
                let max = p_f64(params, "max", 1000.0)?;
                check_range(min, max, "price")?;
                let min_cents = (min * 100.0).ceil() as i64;
                let max_cents = (max * 100.0).floor() as i64;
                check_range(min_cents, max_cents, "price (in cents)")?;
                Provider::Price {
                    min_cents,
                    max_cents,
                }
            }
            "int" => {
                let min = p_i64(params, "min", 0)?;
                let max = p_i64(params, "max", 10_000)?;
                check_range(min, max, "int")?;
                Provider::Int { min, max }
            }
            "float" => {
                let min = p_f64(params, "min", 0.0)?;
                let max = p_f64(params, "max", 1000.0)?;
                check_range(min, max, "float")?;
                Provider::Float {
                    min,
                    max,
                    decimals: p_opt_u32(params, "decimals")?,
                }
            }
            "bool" => {
                let p = p_f64(params, "probability", p_f64(params, "p", 0.5)?)?;
                if !(0.0..=1.0).contains(&p) {
                    return Err(NfError::InvalidParameter(format!(
                        "bool probability must be within [0, 1], got {p}"
                    )));
                }
                Provider::Bool { p }
            }
            "choice" => Self::parse_choice(params)?,
            "date" | "date_of_birth" => {
                let (ds, de) = if canonical(&lower) == "date" {
                    (DEFAULT_DATE_START, DEFAULT_DATE_END)
                } else {
                    (DOB_START, DOB_END)
                };
                let start = p_i64(params, "start", ds)?;
                let end = p_i64(params, "end", de)?;
                check_range(start, end, "date")?;
                let to_i32 = |v: i64| {
                    i32::try_from(v)
                        .map_err(|_| NfError::InvalidParameter(format!("date out of range: {v}")))
                };
                Provider::Date {
                    start: to_i32(start)?,
                    end: to_i32(end)?,
                }
            }
            "datetime" | "iso8601" => {
                let start = p_i64(params, "start", DEFAULT_DT_START_S * MICROS_PER_SEC)?;
                let end = p_i64(params, "end", DEFAULT_DT_END_S * MICROS_PER_SEC)?;
                check_range(start, end, "datetime")?;
                let resolution = match p_str(params, "resolution")?.as_deref() {
                    None | Some("s") | Some("second") | Some("seconds") => MICROS_PER_SEC,
                    Some("ms") | Some("millisecond") | Some("milliseconds") => 1_000,
                    Some("us") | Some("microsecond") | Some("microseconds") => 1,
                    Some(other) => {
                        return Err(NfError::InvalidParameter(format!(
                            "resolution must be one of 's', 'ms', 'us', got {other:?}"
                        )))
                    }
                };
                if canonical(&lower) == "datetime" {
                    Provider::DateTime {
                        start,
                        end,
                        resolution,
                    }
                } else {
                    Provider::Iso8601 {
                        start,
                        end,
                        resolution,
                    }
                }
            }
            "unix_time" => {
                let start = p_i64(params, "start", DEFAULT_DT_START_S)?;
                let end = p_i64(params, "end", DEFAULT_DT_END_S)?;
                check_range(start, end, "unix_time")?;
                Provider::UnixTime { start, end }
            }
            "word" => Provider::Word,
            "sentence" => {
                let min_words = p_i64(params, "min_words", 4)?.max(1) as usize;
                let max_words = p_i64(params, "max_words", 10)?.max(1) as usize;
                check_range(min_words, max_words, "sentence words")?;
                Provider::Sentence {
                    min_words,
                    max_words,
                }
            }
            "paragraph" => {
                let min_sentences = p_i64(params, "min_sentences", 3)?.max(1) as usize;
                let max_sentences = p_i64(params, "max_sentences", 6)?.max(1) as usize;
                check_range(min_sentences, max_sentences, "paragraph sentences")?;
                Provider::Paragraph {
                    min_sentences,
                    max_sentences,
                }
            }
            "serial" => Provider::Serial {
                start: p_i64(params, "start", 1)?,
                step: p_i64(params, "step", 1)?,
            },
            "pattern" => match p_str(params, "pattern")? {
                Some(s) => Provider::Pattern(s.into()),
                None => {
                    return Err(NfError::InvalidParameter(
                        "pattern requires a 'pattern' parameter, e.g. 'ORD-#####'".into(),
                    ))
                }
            },
            "string" => {
                let min_len = p_i64(params, "min_length", 8)?.max(0) as usize;
                let max_len = p_i64(params, "max_length", 16)?.max(0) as usize;
                check_range(min_len, max_len, "string length")?;
                Provider::RandomString { min_len, max_len }
            }
            "password" => Provider::Password {
                length: p_i64(params, "length", 12)?.clamp(4, 1024) as usize,
            },
            "hex_color" => Provider::HexColor,
            "constant" => match params.get("value") {
                Some(Param::Str(s)) => Provider::Constant(s.as_str().into()),
                _ => {
                    return Err(NfError::InvalidParameter(
                        "constant requires a string 'value' parameter".into(),
                    ))
                }
            },
            _ => return Err(NfError::UnknownProvider(name.to_string())),
        };
        Ok(p)
    }

    fn parse_choice(params: &Params) -> Result<Provider> {
        match params.get("values") {
            Some(Param::StrList(v)) if !v.is_empty() => Ok(Provider::ChoiceStr {
                cum_weights: p_weights(params, v.len())?.map(Into::into),
                table: Table::Owned(v.clone().into()),
            }),
            Some(Param::IntList(v)) if !v.is_empty() => Ok(Provider::ChoiceInt {
                cum_weights: p_weights(params, v.len())?.map(Into::into),
                values: v.clone().into(),
            }),
            Some(Param::FloatList(v)) if !v.is_empty() => Ok(Provider::ChoiceFloat {
                cum_weights: p_weights(params, v.len())?.map(Into::into),
                values: v.clone().into(),
            }),
            _ => Err(NfError::InvalidParameter(
                "choice requires a non-empty homogeneous 'values' list (str, int or float)".into(),
            )),
        }
    }

    /// Physical output kind.
    pub fn kind(&self) -> Kind {
        use Provider::*;
        match self {
            Int { .. } | Serial { .. } | UnixTime { .. } | ChoiceInt { .. } => Kind::Int,
            Float { .. } | Price { .. } | Latitude | Longitude | ChoiceFloat { .. } => Kind::Float,
            Bool { .. } => Kind::Bool,
            FirstName
            | LastName
            | City
            | State
            | StateAbbr
            | Country
            | CountryCode
            | CurrencyCode
            | JobTitle
            | Word
            | ChoiceStr { .. } => Kind::Cat,
            Date { .. } => Kind::Date,
            DateTime { .. } => Kind::Timestamp,
            _ => Kind::Str,
        }
    }

    /// The lookup table for [`Kind::Cat`] providers.
    pub fn table(&self, loc: &'static Locale) -> Option<Table> {
        use Provider::*;
        Some(match self {
            FirstName => Table::Static(loc.first_names),
            LastName => Table::Static(loc.last_names),
            City => Table::Static(loc.cities),
            State => Table::Static(loc.states),
            StateAbbr => Table::Static(if loc.state_abbrs.is_empty() {
                loc.states
            } else {
                loc.state_abbrs
            }),
            Country => Table::Static(locales::COUNTRIES),
            CountryCode => Table::Static(locales::COUNTRY_CODES),
            CurrencyCode => Table::Static(locales::CURRENCY_CODES),
            JobTitle => Table::Static(loc.job_titles),
            Word => Table::Static(loc.words),
            ChoiceStr { table, .. } => table.clone(),
            _ => return None,
        })
    }

    /// Typical generated value size in bytes (capacity hint for string buffers).
    fn size_hint(&self) -> usize {
        use Provider::*;
        match self {
            Name | Username => 16,
            Email | DomainName => 26,
            PhoneNumber | Ipv4 | MacAddress | Postcode => 16,
            Ipv6 | Uuid4 | Uuid7 => 39,
            Url => 40,
            UserAgent => 120,
            StreetAddress | Company => 28,
            Address => 60,
            Sentence { .. } => 64,
            Paragraph { .. } => 320,
            Iso8601 { .. } => 20,
            _ => 16,
        }
    }

    // ---------------------------------------------------------------- typed generators

    #[inline]
    fn gen_int<R: Rng>(&self, rng: &mut R, row: u64) -> i64 {
        match self {
            Provider::Int { min, max } => rng.range_i64(*min, *max),
            Provider::Serial { start, step } => {
                start.wrapping_add((row as i64).wrapping_mul(*step))
            }
            Provider::UnixTime { start, end } => rng.range_i64(*start, *end),
            Provider::ChoiceInt {
                values,
                cum_weights,
            } => values[weighted_index(rng, values.len(), cum_weights.as_deref())],
            _ => unreachable!("not an int provider"),
        }
    }

    #[inline]
    fn gen_float<R: Rng>(&self, rng: &mut R) -> f64 {
        match self {
            Provider::Float { min, max, decimals } => {
                let v = min + rng.unit_f64() * (max - min);
                match decimals {
                    Some(d) => round_to(v, *d).clamp(*min, *max),
                    None => v,
                }
            }
            Provider::Price {
                min_cents,
                max_cents,
            } => rng.range_i64(*min_cents, *max_cents) as f64 / 100.0,
            Provider::Latitude => rng.range_i64(-90_000_000, 90_000_000) as f64 / 1e6,
            Provider::Longitude => rng.range_i64(-180_000_000, 180_000_000) as f64 / 1e6,
            Provider::ChoiceFloat {
                values,
                cum_weights,
            } => values[weighted_index(rng, values.len(), cum_weights.as_deref())],
            _ => unreachable!("not a float provider"),
        }
    }

    #[inline]
    fn gen_index<R: Rng>(&self, rng: &mut R, n: usize) -> u32 {
        match self {
            Provider::ChoiceStr { cum_weights, .. } => {
                weighted_index(rng, n, cum_weights.as_deref()) as u32
            }
            _ => rng.below(n) as u32,
        }
    }

    #[inline]
    fn gen_timestamp<R: Rng>(rng: &mut R, start: i64, end: i64, res: i64) -> i64 {
        let lo = start.div_euclid(res) + i64::from(start.rem_euclid(res) != 0);
        let hi = end.div_euclid(res);
        if lo > hi {
            return start;
        }
        rng.range_i64(lo, hi) * res
    }

    /// Append one formatted string value.
    fn write_str<R: Rng>(&self, rng: &mut R, row: u64, ctx: &Ctx, out: &mut String) {
        let loc = ctx.locale;
        match self {
            Provider::Name => write_name(rng, loc, out),
            Provider::Username => write_username(rng, loc, out),
            Provider::Email => write_email(rng, loc, out),
            Provider::PhoneNumber => {
                let fmt = rng_pick(rng, loc.phone_formats);
                expand_pattern(rng, fmt, out);
            }
            Provider::Ipv4 => write_ipv4(rng, out),
            Provider::Ipv6 => write_ipv6(rng, out),
            Provider::MacAddress => write_mac(rng, out),
            Provider::DomainName => write_domain(rng, loc, out),
            Provider::Url => write_url(rng, loc, out),
            Provider::UserAgent => write_user_agent(rng, out),
            Provider::Uuid4 => {
                let mut b = [0u8; 16];
                b[..8].copy_from_slice(&rng.next_u64().to_le_bytes());
                b[8..].copy_from_slice(&rng.next_u64().to_le_bytes());
                push_uuid(out, uuid::Builder::from_random_bytes(b).into_uuid());
            }
            Provider::Uuid7 => {
                let mut r = [0u8; 10];
                r[..8].copy_from_slice(&rng.next_u64().to_le_bytes());
                r[8..].copy_from_slice(&rng.next_u32().to_le_bytes()[..2]);
                let ms = ctx.uuid7_base_ms.wrapping_add(row) & 0xFFFF_FFFF_FFFF;
                push_uuid(
                    out,
                    uuid::Builder::from_unix_timestamp_millis(ms, &r).into_uuid(),
                );
            }
            Provider::StreetAddress => write_street_address(rng, loc, out),
            Provider::Postcode => write_postcode(rng, loc, out),
            Provider::Address => write_address(rng, loc, out),
            Provider::Company => write_company(rng, loc, out),
            Provider::CreditCardNumber => write_credit_card(rng, out),
            Provider::Iso8601 {
                start,
                end,
                resolution,
            } => {
                push_datetime(out, Self::gen_timestamp(rng, *start, *end, *resolution));
            }
            Provider::Sentence {
                min_words,
                max_words,
            } => {
                let n = rng.range_i64(*min_words as i64, *max_words as i64) as usize;
                write_sentence(rng, loc, n, out);
            }
            Provider::Paragraph {
                min_sentences,
                max_sentences,
            } => {
                let n = rng.range_i64(*min_sentences as i64, *max_sentences as i64) as usize;
                for i in 0..n {
                    if i > 0 {
                        out.push_str(loc.sentence_sep);
                    }
                    let w = rng.range_i64(4, 10) as usize;
                    write_sentence(rng, loc, w, out);
                }
            }
            Provider::Pattern(p) => expand_pattern(rng, p, out),
            Provider::RandomString { min_len, max_len } => {
                const ALNUM: &[u8] =
                    b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
                let n = rng.range_i64(*min_len as i64, *max_len as i64) as usize;
                for _ in 0..n {
                    out.push(*rng.pick(ALNUM) as char);
                }
            }
            Provider::Password { length } => write_password(rng, *length, out),
            Provider::HexColor => {
                out.push('#');
                push_hex(out, u64::from(rng.next_u32() & 0xFF_FFFF), 6);
            }
            Provider::Constant(s) => out.push_str(s),
            _ => unreachable!("not a string provider: {self:?}"),
        }
    }
}

#[inline]
fn rng_pick<'a, R: Rng>(rng: &mut R, items: &'a [&'a str]) -> &'a str {
    items[rng.below(items.len())]
}

#[inline]
fn weighted_index<R: Rng>(rng: &mut R, n: usize, cum: Option<&[f64]>) -> usize {
    match cum {
        None => rng.below(n),
        Some(cum) => {
            let total = cum[cum.len() - 1];
            let u = rng.unit_f64() * total;
            cum.partition_point(|c| *c <= u).min(n - 1)
        }
    }
}

#[inline]
fn round_to(v: f64, decimals: u32) -> f64 {
    let f = 10f64.powi(decimals as i32);
    (v * f).round() / f
}

