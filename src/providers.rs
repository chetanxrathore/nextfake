//! Value providers.
//!
//! A [`Provider`] is a fully-parsed, immutable description of how to generate one column of
//! values. Generation is a pure function of the RNG state, the global row index and the
//! [`Ctx`]; providers never allocate per row except to append into the column's output buffer.

