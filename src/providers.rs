// ---------------------------------------------------------------------------------------------
// Output kinds & column data
// ---------------------------------------------------------------------------------------------

/// Physical output kind of a provider (maps 1:1 onto an Arrow data type).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// `Int64`
    Int,
    /// `Float64`
    Float,
    /// `Boolean`
    Bool,
    /// `Utf8`, generated by formatting
    Str,
    /// `Utf8`, generated as an index into a static/shared string table
    Cat,
    /// `Date32` (days since the Unix epoch)
    Date,
    /// `Timestamp(Microsecond, None)`
    Timestamp,
}

/// A string lookup table backing a [`Kind::Cat`] column.
#[derive(Debug, Clone)]
pub enum Table {
    Static(&'static [&'static str]),
    Owned(Arc<[String]>),
}

impl Table {
    #[inline]
    pub fn len(&self) -> usize {
        match self {
            Table::Static(t) => t.len(),
            Table::Owned(t) => t.len(),
        }
    }

    #[inline]
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    #[inline]
    pub fn get(&self, i: usize) -> &str {
        match self {
            Table::Static(t) => t[i],
            Table::Owned(t) => &t[i],
        }
    }

    /// A stable identity for caching converted values (e.g. Python strings).
    pub fn ptr_id(&self) -> usize {
        match self {
            Table::Static(t) => t.as_ptr() as usize,
            Table::Owned(t) => t.as_ptr() as usize,
        }
    }
}

/// Generated values for one column of one chunk.
#[derive(Debug, Clone)]
pub enum Data {
    Int(Vec<i64>),
    Float(Vec<f64>),
    Bool(Vec<bool>),
    /// UTF-8 values; `offsets` has `len + 1` entries.
    Str {
        offsets: Vec<i32>,
        data: String,
    },
    /// Indices into `table`.
    Cat {
        idx: Vec<u32>,
        table: Table,
    },
    Date(Vec<i32>),
    Timestamp(Vec<i64>),
}

/// One column of one chunk plus its validity (`None` = no nulls).
#[derive(Debug, Clone)]
pub struct Column {
    pub data: Data,
    /// `true` = valid, `false` = null.
    pub validity: Option<Vec<bool>>,
}

impl Column {
    pub fn len(&self) -> usize {
        match &self.data {
            Data::Int(v) => v.len(),
            Data::Float(v) => v.len(),
            Data::Bool(v) => v.len(),
            Data::Str { offsets, .. } => offsets.len() - 1,
            Data::Cat { idx, .. } => idx.len(),
            Data::Date(v) => v.len(),
            Data::Timestamp(v) => v.len(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    #[inline]
    pub fn is_valid(&self, i: usize) -> bool {
        self.validity.as_ref().is_none_or(|v| v[i])
    }

    /// String value at row `i` for `Str`/`Cat` columns.
    #[inline]
    pub fn str_at(&self, i: usize) -> Option<&str> {
        match &self.data {
            Data::Str { offsets, data } => {
                Some(&data[offsets[i] as usize..offsets[i + 1] as usize])
            }
            Data::Cat { idx, table } => Some(table.get(idx[i] as usize)),
            _ => None,
        }
    }
}

/// Per-generation context shared by all columns.
#[derive(Debug, Clone, Copy)]
pub struct Ctx {
    pub locale: &'static Locale,
    /// Millisecond timestamp of row 0 for UUIDv7 generation.
    pub uuid7_base_ms: u64,
}

