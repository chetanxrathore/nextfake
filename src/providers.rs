#[inline]
fn null_draw<R: Rng>(rng: &mut R, null_p: f64, validity: &mut Option<Vec<bool>>) -> bool {
    match validity {
        None => false,
        Some(v) => {
            let is_null = rng.chance(null_p);
            v.push(!is_null);
            is_null
        }
    }
}

/// Generate `len` values of `provider` for rows `row_start..row_start + len`.
pub fn generate_column<R: Rng>(
    provider: &Provider,
    ctx: &Ctx,
    rng: &mut R,
    row_start: u64,
    len: usize,
    null_p: f64,
) -> Column {
    let mut validity = (null_p > 0.0).then(|| Vec::with_capacity(len));
    let data = match provider.kind() {
        Kind::Int => {
            let mut v = Vec::with_capacity(len);
            for i in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    v.push(0);
                } else {
                    v.push(provider.gen_int(rng, row_start + i as u64));
                }
            }
            Data::Int(v)
        }
        Kind::Float => {
            let mut v = Vec::with_capacity(len);
            for _ in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    v.push(0.0);
                } else {
                    v.push(provider.gen_float(rng));
                }
            }
            Data::Float(v)
        }
        Kind::Bool => {
            let p = match provider {
                Provider::Bool { p } => *p,
                _ => 0.5,
            };
            let mut v = Vec::with_capacity(len);
            for _ in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    v.push(false);
                } else {
                    v.push(rng.chance(p));
                }
            }
            Data::Bool(v)
        }
        Kind::Cat => {
            let table = provider
                .table(ctx.locale)
                .expect("categorical provider has a table");
            let n = table.len();
            let mut idx = Vec::with_capacity(len);
            for _ in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    idx.push(0);
                } else {
                    idx.push(provider.gen_index(rng, n));
                }
            }
            Data::Cat { idx, table }
        }
        Kind::Date => {
            let (s, e) = match provider {
                Provider::Date { start, end } => (*start, *end),
                _ => unreachable!(),
            };
            let mut v = Vec::with_capacity(len);
            for _ in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    v.push(0);
                } else {
                    v.push(rng.range_i64(i64::from(s), i64::from(e)) as i32);
                }
            }
            Data::Date(v)
        }
        Kind::Timestamp => {
            let (s, e, res) = match provider {
                Provider::DateTime {
                    start,
                    end,
                    resolution,
                } => (*start, *end, *resolution),
                _ => unreachable!(),
            };
            let mut v = Vec::with_capacity(len);
            for _ in 0..len {
                if null_draw(rng, null_p, &mut validity) {
                    v.push(0);
                } else {
                    v.push(Provider::gen_timestamp(rng, s, e, res));
                }
            }
            Data::Timestamp(v)
        }
        Kind::Str => {
            let mut offsets = Vec::with_capacity(len + 1);
            offsets.push(0i32);
            let mut data = String::with_capacity(len * provider.size_hint());
            for i in 0..len {
                if !null_draw(rng, null_p, &mut validity) {
                    provider.write_str(rng, row_start + i as u64, ctx, &mut data);
                }
                offsets.push(i32::try_from(data.len()).expect("chunk string data exceeds 2 GiB"));
            }
            Data::Str { offsets, data }
        }
    };
    Column { data, validity }
}

