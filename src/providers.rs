#[inline]
fn push_num(out: &mut String, v: impl itoa::Integer) {
    out.push_str(itoa::Buffer::new().format(v));
}

#[inline]
fn push_hex(out: &mut String, v: u64, width: usize) {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    for i in (0..width).rev() {
        out.push(HEX[((v >> (i * 4)) & 0xF) as usize] as char);
    }
}

fn push_uuid(out: &mut String, u: uuid::Uuid) {
    let mut buf = [0u8; uuid::fmt::Hyphenated::LENGTH];
    out.push_str(u.hyphenated().encode_lower(&mut buf));
}

fn push_digits<R: Rng>(rng: &mut R, n: usize, out: &mut String) {
    for _ in 0..n {
        out.push(rng.digit() as char);
    }
}

/// Expand a template: `#` → 0-9, `%` → 1-9, `^` → 2-9, `?` → A-Z, `!` → a-z,
/// `*` → [A-Za-z0-9]; `\` escapes the next character; anything else is copied.
pub fn expand_pattern<R: Rng>(rng: &mut R, pattern: &str, out: &mut String) {
    let mut escaped = false;
    for ch in pattern.chars() {
        if escaped {
            out.push(ch);
            escaped = false;
            continue;
        }
        match ch {
            '\\' => escaped = true,
            '#' => out.push(rng.digit() as char),
            '%' => out.push((b'1' + rng.below(9) as u8) as char),
            '^' => out.push((b'2' + rng.below(8) as u8) as char),
            '?' => out.push((b'A' + rng.below(26) as u8) as char),
            '!' => out.push((b'a' + rng.below(26) as u8) as char),
            '*' => {
                const ALNUM: &[u8] =
                    b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
                out.push(*rng.pick(ALNUM) as char);
            }
            c => out.push(c),
        }
    }
}

fn write_name<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let first = rng_pick(rng, loc.first_names);
    let last = rng_pick(rng, loc.last_names);
    match loc.name_order {
        NameOrder::FirstLast => {
            out.push_str(first);
            out.push(' ');
            out.push_str(last);
        }
        NameOrder::LastFirst => {
            out.push_str(last);
            out.push(' ');
            out.push_str(first);
        }
    }
}

fn ascii_names<R: Rng>(rng: &mut R, loc: &'static Locale) -> (&'static str, &'static str) {
    let d: &'static locales::Derived = loc.derived();
    let f = &d.first_ascii[rng.below(d.first_ascii.len())];
    let l = &d.last_ascii[rng.below(d.last_ascii.len())];
    (f.as_str(), l.as_str())
}

#[inline]
fn first_char(s: &str) -> &str {
    &s[..1.min(s.len())]
}

fn write_username<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let (f, l) = ascii_names(rng, loc);
    match rng.below(6) {
        0 => {
            out.push_str(f);
            out.push('.');
            out.push_str(l);
        }
        1 => {
            out.push_str(f);
            out.push_str(l);
            push_digits(rng, 2, out);
        }
        2 => {
            out.push_str(f);
            out.push('_');
            out.push_str(l);
        }
        3 => {
            out.push_str(first_char(f));
            out.push_str(l);
            push_digits(rng, 2, out);
        }
        4 => {
            out.push_str(l);
            out.push_str(first_char(f));
        }
        _ => {
            out.push_str(f);
            push_num(out, rng.range_i64(1, 9999));
        }
    }
}

fn write_email<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let (f, l) = ascii_names(rng, loc);
    match rng.below(8) {
        0 | 1 => {
            out.push_str(f);
            out.push('.');
            out.push_str(l);
        }
        2 => {
            out.push_str(f);
            out.push_str(l);
            push_digits(rng, 2, out);
        }
        3 => {
            out.push_str(first_char(f));
            out.push_str(l);
        }
        4 => {
            out.push_str(f);
            out.push('_');
            out.push_str(l);
        }
        5 => {
            out.push_str(l);
            out.push('.');
            out.push_str(f);
            push_num(out, rng.range_i64(1, 99));
        }
        6 => {
            out.push_str(f);
            push_num(out, rng.range_i64(10, 9999));
        }
        _ => {
            out.push_str(first_char(f));
            out.push('.');
            out.push_str(l);
            push_digits(rng, 2, out);
        }
    }
    out.push('@');
    if rng.below(10) < 8 {
        out.push_str(rng_pick(rng, loc.free_email_domains));
    } else {
        let (_, l2) = ascii_names(rng, loc);
        out.push_str(l2);
        out.push('.');
        out.push_str(rng_pick(rng, loc.tlds));
    }
}

fn write_ipv4<R: Rng>(rng: &mut R, out: &mut String) {
    // Public-looking unicast first octet: 1..=223 excluding 10 and 127.
    let first = loop {
        let v = rng.range_i64(1, 223);
        if v != 10 && v != 127 {
            break v;
        }
    };
    push_num(out, first);
    for i in 0..3 {
        out.push('.');
        let v = if i == 2 {
            rng.range_i64(1, 254)
        } else {
            rng.range_i64(0, 255)
        };
        push_num(out, v);
    }
}

fn write_ipv6<R: Rng>(rng: &mut R, out: &mut String) {
    // Global unicast (2000::/3) with full (uncompressed, no leading zeros) groups.
    let a = rng.next_u64();
    let b = rng.next_u64();
    for i in 0..8 {
        if i > 0 {
            out.push(':');
        }
        let word = if i < 4 {
            a >> (48 - 16 * i)
        } else {
            b >> (48 - 16 * (i - 4))
        } & 0xFFFF;
        let word = if i == 0 {
            0x2000 | (word & 0x1FFF)
        } else {
            word
        };
        let width = if word >= 0x1000 {
            4
        } else if word >= 0x100 {
            3
        } else if word >= 0x10 {
            2
        } else {
            1
        };
        push_hex(out, word, width);
    }
}

fn write_mac<R: Rng>(rng: &mut R, out: &mut String) {
    let v = rng.next_u64();
    for i in 0..6 {
        if i > 0 {
            out.push(':');
        }
        let mut byte = (v >> (8 * i)) & 0xFF;
        if i == 0 {
            byte &= 0xFE; // unicast
        }
        push_hex(out, byte, 2);
    }
}

fn write_domain<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let (_, l) = ascii_names(rng, loc);
    match rng.below(4) {
        0 => {
            let (_, l2) = ascii_names(rng, loc);
            out.push_str(l);
            out.push('-');
            out.push_str(l2);
        }
        1 => {
            out.push_str(rng_pick(rng, locales::WORDS_EN));
            out.push_str(l);
        }
        _ => out.push_str(l),
    }
    out.push('.');
    out.push_str(rng_pick(rng, loc.tlds));
}

fn write_url<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let variant = rng.below(5);
    out.push_str(if variant == 4 { "http://" } else { "https://" });
    if variant % 2 == 0 {
        out.push_str("www.");
    }
    write_domain(rng, loc, out);
    out.push('/');
    match variant {
        2 => {
            out.push_str(rng_pick(rng, locales::WORDS_EN));
            out.push('/');
        }
        3 | 4 => {
            out.push_str(rng_pick(rng, locales::WORDS_EN));
            out.push('/');
            out.push_str(rng_pick(rng, locales::WORDS_EN));
            out.push_str(".html");
        }
        _ => {}
    }
}

fn write_user_agent<R: Rng>(rng: &mut R, out: &mut String) {
    let tpl = rng_pick(rng, locales::USER_AGENTS);
    let mut rest = tpl;
    while let Some(open) = rest.find('{') {
        out.push_str(&rest[..open]);
        let close = rest[open..].find('}').map_or(rest.len(), |c| open + c);
        let token = &rest[open + 1..close];
        let v = match token {
            "CH" => rng.range_i64(118, 140),
            "FF" => rng.range_i64(115, 145),
            "SF" => rng.range_i64(15, 19),
            "IOS" => rng.range_i64(15, 19),
            "AND" => rng.range_i64(11, 15),
            "PX" => rng.range_i64(6, 9),
            _ => rng.range_i64(0, 6),
        };
        push_num(out, v);
        rest = &rest[(close + 1).min(rest.len())..];
    }
    out.push_str(rest);
}

fn write_street_address<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    match loc.style {
        AddressStyle::Us => {
            let digits = rng.range_i64(3, 5) as u32;
            push_num(
                out,
                rng.range_i64(10i64.pow(digits - 1), 10i64.pow(digits) - 1),
            );
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_names));
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_suffixes));
            match rng.below(10) {
                0 => {
                    out.push_str(" Apt. ");
                    push_num(out, rng.range_i64(1, 999));
                }
                1 => {
                    out.push_str(" Suite ");
                    push_num(out, rng.range_i64(100, 999));
                }
                _ => {}
            }
        }
        AddressStyle::Gb => {
            if rng.below(10) == 0 {
                out.push_str("Flat ");
                push_num(out, rng.range_i64(1, 40));
                out.push_str(", ");
            }
            push_num(out, rng.range_i64(1, 299));
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_names));
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_suffixes));
        }
        AddressStyle::De => {
            out.push_str(rng_pick(rng, loc.street_names));
            out.push(' ');
            push_num(out, rng.range_i64(1, 199));
            if rng.below(10) == 0 {
                out.push((b'a' + rng.below(3) as u8) as char);
            }
        }
        AddressStyle::Fr => {
            push_num(out, rng.range_i64(1, 199));
            match rng.below(20) {
                0 => out.push_str(" bis"),
                1 => out.push_str(" ter"),
                _ => {}
            }
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_suffixes));
            out.push(' ');
            out.push_str(rng_pick(rng, loc.street_names));
        }
        AddressStyle::Jp => {
            out.push_str(rng_pick(rng, loc.street_names));
            let chome = rng.range_i64(1, 9);
            let ban = rng.range_i64(1, 30);
            let go = rng.range_i64(1, 20);
            if rng.below(2) == 0 {
                push_num(out, chome);
                out.push_str("丁目");
                push_num(out, ban);
                out.push('番');
                push_num(out, go);
                out.push('号');
            } else {
                push_num(out, chome);
                out.push('-');
                push_num(out, ban);
                out.push('-');
                push_num(out, go);
            }
        }
    }
}

fn write_postcode<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    match loc.style {
        AddressStyle::Us => {
            let zip = rng.range_i64(1001, 99950);
            if zip < 10000 {
                out.push('0');
            }
            push_num(out, zip);
        }
        AddressStyle::Gb => {
            const UNIT: &[u8] = b"ABDEFGHJLNPQRSTUWXYZ";
            out.push_str(rng_pick(rng, locales_gb_areas()));
            push_num(out, rng.range_i64(1, 20));
            out.push(' ');
            out.push(rng.digit() as char);
            out.push(*rng.pick(UNIT) as char);
            out.push(*rng.pick(UNIT) as char);
        }
        AddressStyle::De => {
            let plz = rng.range_i64(1067, 99998);
            if plz < 10000 {
                out.push('0');
            }
            push_num(out, plz);
        }
        AddressStyle::Fr => {
            let dept = loop {
                let d = rng.range_i64(1, 95);
                if d != 20 {
                    break d;
                }
            };
            push_2(out, dept as u32);
            push_digits(rng, 2, out);
            out.push(if rng.below(3) == 0 {
                rng.digit() as char
            } else {
                '0'
            });
        }
        AddressStyle::Jp => {
            push_digits(rng, 3, out);
            out.push('-');
            push_digits(rng, 4, out);
        }
    }
}

fn locales_gb_areas() -> &'static [&'static str] {
    locales::gb_postcode_areas()
}

fn write_address<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    match loc.style {
        AddressStyle::Us => {
            write_street_address(rng, loc, out);
            out.push_str(", ");
            out.push_str(rng_pick(rng, loc.cities));
            out.push_str(", ");
            out.push_str(rng_pick(rng, loc.state_abbrs));
            out.push(' ');
            write_postcode(rng, loc, out);
        }
        AddressStyle::Gb => {
            write_street_address(rng, loc, out);
            out.push_str(", ");
            out.push_str(rng_pick(rng, loc.cities));
            out.push(' ');
            write_postcode(rng, loc, out);
        }
        AddressStyle::De | AddressStyle::Fr => {
            write_street_address(rng, loc, out);
            out.push_str(", ");
            write_postcode(rng, loc, out);
            out.push(' ');
            out.push_str(rng_pick(rng, loc.cities));
        }
        AddressStyle::Jp => {
            out.push('〒');
            write_postcode(rng, loc, out);
            out.push(' ');
            out.push_str(rng_pick(rng, loc.states));
            out.push_str(rng_pick(rng, loc.cities));
            write_street_address(rng, loc, out);
        }
    }
}

fn write_company<R: Rng>(rng: &mut R, loc: &'static Locale, out: &mut String) {
    let tpl = rng_pick(rng, loc.company_formats);
    let mut chars = tpl.char_indices().peekable();
    while let Some((i, ch)) = chars.next() {
        if ch == '{' && tpl[i..].len() >= 3 && tpl.as_bytes()[i + 2] == b'}' {
            match tpl.as_bytes()[i + 1] {
                b'L' => out.push_str(rng_pick(rng, loc.last_names)),
                b'S' if !loc.company_suffixes.is_empty() => {
                    out.push_str(rng_pick(rng, loc.company_suffixes));
                }
                b'W' if !loc.company_words.is_empty() => {
                    out.push_str(rng_pick(rng, loc.company_words));
                }
                _ => {}
            }
            chars.next();
            chars.next();
        } else {
            out.push(ch);
        }
    }
}

/// Luhn check digit for an ASCII digit payload.
pub fn luhn_check_digit(payload: &[u8]) -> u8 {
    let mut sum = 0u32;
    for (i, d) in payload.iter().rev().enumerate() {
        let mut v = u32::from(d - b'0');
        if i % 2 == 0 {
            v *= 2;
            if v > 9 {
                v -= 9;
            }
        }
        sum += v;
    }
    b'0' + ((10 - sum % 10) % 10) as u8
}

/// Validate a digit string with the Luhn algorithm.
pub fn luhn_valid(number: &str) -> bool {
    let b = number.as_bytes();
    !b.is_empty()
        && b.iter().all(u8::is_ascii_digit)
        && luhn_check_digit(&b[..b.len() - 1]) == b[b.len() - 1]
}

fn write_credit_card<R: Rng>(rng: &mut R, out: &mut String) {
    let mut buf = [0u8; 19];
    let (prefix, len): (&str, usize) = match rng.below(10) {
        0..=3 | 9 => ("4", 16), // Visa
        4 | 5 => {
            // Mastercard 51-55
            let p = ["51", "52", "53", "54", "55"];
            (p[rng.below(5)], 16)
        }
        6 => ("2221", 16), // Mastercard 2-series (2221-2720 range start)
        7 => (if rng.below(2) == 0 { "34" } else { "37" }, 15), // Amex
        _ => ("6011", 16), // Discover
    };
    buf[..prefix.len()].copy_from_slice(prefix.as_bytes());
    let mut n = prefix.len();
    if prefix == "2221" {
        // Spread across the full 2221..=2720 Mastercard range.
        let v = rng.range_i64(2221, 2720).to_string();
        buf[..4].copy_from_slice(v.as_bytes());
    }
    while n < len - 1 {
        buf[n] = rng.digit();
        n += 1;
    }
    buf[len - 1] = luhn_check_digit(&buf[..len - 1]);
    // All bytes are ASCII digits.
    out.push_str(std::str::from_utf8(&buf[..len]).expect("ascii digits"));
}

fn push_capitalized(out: &mut String, word: &str) {
    let mut chars = word.chars();
    if let Some(c) = chars.next() {
        out.extend(c.to_uppercase());
        out.push_str(chars.as_str());
    }
}

fn write_sentence<R: Rng>(rng: &mut R, loc: &'static Locale, n: usize, out: &mut String) {
    for i in 0..n {
        let w = rng_pick(rng, loc.words);
        if i == 0 {
            if loc.capitalize {
                push_capitalized(out, w);
            } else {
                out.push_str(w);
            }
        } else {
            out.push_str(loc.word_sep);
            out.push_str(w);
        }
    }
    out.push_str(loc.sentence_end);
}

fn write_password<R: Rng>(rng: &mut R, length: usize, out: &mut String) {
    const LOWER: &[u8] = b"abcdefghijklmnopqrstuvwxyz";
    const UPPER: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    const DIGIT: &[u8] = b"0123456789";
    const SYMBOL: &[u8] = b"!@#$%^&*()-_=+[]{}?";
    const ALL: &[u8] =
        b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()-_=+[]{}?";
    let mut buf: Vec<u8> = Vec::with_capacity(length);
    buf.push(*rng.pick(LOWER));
    buf.push(*rng.pick(UPPER));
    buf.push(*rng.pick(DIGIT));
    buf.push(*rng.pick(SYMBOL));
    while buf.len() < length {
        buf.push(*rng.pick(ALL));
    }
    for i in (1..buf.len()).rev() {
        let j = rng.below(i + 1);
        buf.swap(i, j);
    }
    out.push_str(std::str::from_utf8(&buf).expect("ascii password"));
}

