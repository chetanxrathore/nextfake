/// A loosely-typed provider parameter, as received from Python or a schema file.
#[derive(Debug, Clone, PartialEq)]
pub enum Param {
    Null,
    Bool(bool),
    Int(i64),
    Float(f64),
    Str(String),
    StrList(Vec<String>),
    IntList(Vec<i64>),
    FloatList(Vec<f64>),
}

/// Named provider parameters.
pub type Params = HashMap<String, Param>;

fn p_i64(params: &Params, key: &str, default: i64) -> Result<i64> {
    match params.get(key) {
        None | Some(Param::Null) => Ok(default),
        Some(Param::Int(v)) => Ok(*v),
        Some(Param::Float(v)) if v.fract() == 0.0 && v.is_finite() => Ok(*v as i64),
        Some(other) => Err(NfError::InvalidParameter(format!(
            "{key} must be an integer, got {other:?}"
        ))),
    }
}

fn p_f64(params: &Params, key: &str, default: f64) -> Result<f64> {
    match params.get(key) {
        None | Some(Param::Null) => Ok(default),
        Some(Param::Int(v)) => Ok(*v as f64),
        Some(Param::Float(v)) if v.is_finite() => Ok(*v),
        Some(other) => Err(NfError::InvalidParameter(format!(
            "{key} must be a finite number, got {other:?}"
        ))),
    }
}

fn p_opt_u32(params: &Params, key: &str) -> Result<Option<u32>> {
    match params.get(key) {
        None | Some(Param::Null) => Ok(None),
        Some(Param::Int(v)) if (0..=15).contains(v) => Ok(Some(*v as u32)),
        Some(other) => Err(NfError::InvalidParameter(format!(
            "{key} must be an integer in 0..=15, got {other:?}"
        ))),
    }
}

fn p_str(params: &Params, key: &str) -> Result<Option<String>> {
    match params.get(key) {
        None | Some(Param::Null) => Ok(None),
        Some(Param::Str(s)) => Ok(Some(s.clone())),
        Some(other) => Err(NfError::InvalidParameter(format!(
            "{key} must be a string, got {other:?}"
        ))),
    }
}

fn p_weights(params: &Params, n: usize) -> Result<Option<Vec<f64>>> {
    let w: Vec<f64> = match params.get("weights") {
        None | Some(Param::Null) => return Ok(None),
        Some(Param::FloatList(w)) => w.clone(),
        Some(Param::IntList(w)) => w.iter().map(|v| *v as f64).collect(),
        Some(other) => {
            return Err(NfError::InvalidParameter(format!(
                "weights must be a list of numbers, got {other:?}"
            )))
        }
    };
    if w.len() != n {
        return Err(NfError::InvalidParameter(format!(
            "weights has {} entries but there are {n} values",
            w.len()
        )));
    }
    if w.iter().any(|x| !x.is_finite() || *x < 0.0) || w.iter().sum::<f64>() <= 0.0 {
        return Err(NfError::InvalidParameter(
            "weights must be non-negative and sum to a positive value".into(),
        ));
    }
    let mut acc = 0.0;
    Ok(Some(
        w.into_iter()
            .map(|x| {
                acc += x;
                acc
            })
            .collect(),
    ))
}

fn check_range<T: PartialOrd + std::fmt::Debug>(lo: T, hi: T, what: &str) -> Result<()> {
    if lo > hi {
        return Err(NfError::InvalidParameter(format!(
            "{what}: min/start ({lo:?}) must be <= max/end ({hi:?})"
        )));
    }
    Ok(())
}

// ---------------------------------------------------------------------------------------------
// Time helpers (proleptic Gregorian, Howard Hinnant's algorithms)
// ---------------------------------------------------------------------------------------------

pub const MICROS_PER_SEC: i64 = 1_000_000;
pub const SECS_PER_DAY: i64 = 86_400;

/// Days since 1970-01-01 for a civil date.
pub const fn days_from_civil(y: i64, m: u32, d: u32) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m as i64 + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d as i64 - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Civil date `(year, month, day)` for days since 1970-01-01.
pub const fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

/// Broken-down UTC timestamp.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Civil {
    pub year: i64,
    pub month: u32,
    pub day: u32,
    pub hour: u32,
    pub minute: u32,
    pub second: u32,
    pub micro: u32,
}

/// Break epoch microseconds into civil components.
pub fn civil_from_micros(us: i64) -> Civil {
    let secs = us.div_euclid(MICROS_PER_SEC);
    let micro = us.rem_euclid(MICROS_PER_SEC) as u32;
    let days = secs.div_euclid(SECS_PER_DAY);
    let sod = secs.rem_euclid(SECS_PER_DAY) as u32;
    let (year, month, day) = civil_from_days(days);
    Civil {
        year,
        month,
        day,
        hour: sod / 3600,
        minute: (sod / 60) % 60,
        second: sod % 60,
        micro,
    }
}

#[inline]
fn push_2(out: &mut String, v: u32) {
    out.push((b'0' + (v / 10) as u8) as char);
    out.push((b'0' + (v % 10) as u8) as char);
}

#[inline]
fn push_year(out: &mut String, y: i64) {
    if (0..=9999).contains(&y) {
        let y = y as u32;
        push_2(out, y / 100);
        push_2(out, y % 100);
    } else {
        out.push_str(itoa::Buffer::new().format(y));
    }
}

/// Append an ISO-8601 date (`YYYY-MM-DD`).
pub fn push_date(out: &mut String, days: i32) {
    let (y, m, d) = civil_from_days(i64::from(days));
    push_year(out, y);
    out.push('-');
    push_2(out, m);
    out.push('-');
    push_2(out, d);
}

/// Append an ISO-8601 local datetime (`YYYY-MM-DDTHH:MM:SS[.ffffff]`).
pub fn push_datetime(out: &mut String, us: i64) {
    let c = civil_from_micros(us);
    push_year(out, c.year);
    out.push('-');
    push_2(out, c.month);
    out.push('-');
    push_2(out, c.day);
    out.push('T');
    push_2(out, c.hour);
    out.push(':');
    push_2(out, c.minute);
    out.push(':');
    push_2(out, c.second);
    if c.micro != 0 {
        out.push('.');
        let s = c.micro;
        push_2(out, s / 10_000);
        push_2(out, (s / 100) % 100);
        push_2(out, s % 100);
    }
}

// Default temporal ranges are fixed (not relative to "now") so a seed reproduces forever.
const DEFAULT_DT_START_S: i64 = days_from_civil(2020, 1, 1) * SECS_PER_DAY;
const DEFAULT_DT_END_S: i64 = days_from_civil(2026, 1, 1) * SECS_PER_DAY - 1;
const DEFAULT_DATE_START: i64 = days_from_civil(2000, 1, 1);
const DEFAULT_DATE_END: i64 = days_from_civil(2025, 12, 31);
const DOB_START: i64 = days_from_civil(1940, 1, 1);
const DOB_END: i64 = days_from_civil(2007, 12, 31);

